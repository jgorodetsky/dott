#!/usr/bin/env bash
# notices.sh - writes THIRD_PARTY_NOTICES.md: the license of every module built into dott.
# test-only modules are left out, since they are not in the binary.
#   scripts/notices.sh           write the file
#   scripts/notices.sh --check   fail if the file is out of date (check.sh runs this)
set -euo pipefail
cd "$(dirname "$0")/.."

render() {
  printf '# Third-party notices\n\n'
  printf 'dott is built with these modules. Generated by scripts/notices.sh; do not edit by hand.\n'
  go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}@{{.Version}}	{{.Dir}}{{end}}{{end}}' ./cmd/dott |
    sort -u | while IFS=$'\t' read -r mod dir; do
      lic=""
      for f in LICENSE LICENSE.md LICENSE.txt LICENCE COPYING; do
        [ -f "$dir/$f" ] && { lic="$dir/$f"; break; }
      done
      [ -n "$lic" ] || { echo "no license file in $mod" >&2; exit 1; }
      printf '\n## %s\n\n```\n' "$mod"
      cat "$lic"
      printf '```\n'
    done
}

if [ "${1:-}" = "--check" ]; then
  if ! diff -q <(render) THIRD_PARTY_NOTICES.md >/dev/null 2>&1; then
    echo "THIRD_PARTY_NOTICES.md is out of date: run scripts/notices.sh" >&2
    exit 1
  fi
else
  render > THIRD_PARTY_NOTICES.md
fi
